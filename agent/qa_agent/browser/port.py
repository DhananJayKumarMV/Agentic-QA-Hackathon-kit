"""The interface between the Executor (workstream D) and the browser layer (workstream C).

D codes against this Protocol and tests with a stub; C implements it with Playwright.
"""
from typing import Any, Protocol

from ..contracts import Evidence, NetworkEvent, Target


class ResolvedElement(Protocol):
    """Thin wrapper over a Playwright Locator, so D never imports Playwright directly."""

    async def click(self) -> None: ...
    async def fill(self, value: str) -> None: ...
    async def select(self, value: str) -> None: ...
    async def text(self) -> str: ...
    async def all_texts(self) -> list[str]: ...
    async def attribute(self, name: str) -> str | None: ...
    async def is_visible(self) -> bool: ...
    async def is_disabled(self) -> bool: ...
    async def count(self) -> int: ...


class BrowserPort(Protocol):
    base_url: str

    async def goto(self, path: str) -> None: ...
    async def reload(self) -> None: ...
    async def back(self) -> None: ...
    async def set_viewport(self, width: int, height: int) -> None: ...
    async def current_url(self) -> str: ...

    async def resolve(self, target: Target) -> tuple[ResolvedElement, str, bool]:
        """Return (element, locator description used, whether it was healed by the LLM)."""
        ...

    async def settle(self, timeout_ms: int = 10_000) -> None:
        """Wait until network is quiet, nothing is aria-busy, no loading text, DOM stable."""
        ...

    async def evaluate(self, js: str, arg: Any = None) -> Any: ...

    async def api_request(self, method: str, path: str, body: Any = None) -> NetworkEvent:
        """Call the app's API with the browser session's cookies (for snapshots and compensation)."""
        ...

    def network_log(self) -> list[NetworkEvent]: ...
    def clear_network_log(self) -> None: ...

    async def delay_requests(self, method: str, url_glob: str, delay_ms: int) -> None:
        """Hold matching requests for delay_ms (used to observe in-flight UI state)."""
        ...

    async def screenshot(self, name: str, highlight: Target | None = None) -> Evidence: ...
    async def aria_snapshot(self, max_chars: int = 12_000) -> str: ...

    async def new_context(self, fresh: bool = False) -> None:
        """Start a new browser context; fresh=True drops cookies and storage."""
        ...

    async def close(self) -> None: ...
